// auxlatCoeffs is pj_auxlat_coeffs: the Fourier coefficients converting
// auxiliary latitude auxin to auxout.
func auxlatCoeffs(n float64, auxin, auxout int) [auxOrder]float64 {
	var f [auxOrder]float64
	k := auxNumber*auxout + auxin
	o := auxPtrs[k]
	if o == auxPtrs[k+1] {
		panic("geozarr: unsupported conversion between auxiliary latitudes")
	}
	d, n2 := n, n*n
	if auxin <= auxRectifying && auxout <= auxRectifying {
		for l := range auxOrder {
			m := (auxOrder - l - 1) / 2
			f[l] = d * polyval(n2, auxCoeffs[o:], m)
			o += m + 1
			d *= n
		}
	} else {
		for l := range auxOrder {
			m := auxOrder - l - 1
			f[l] = d * polyval(n, auxCoeffs[o:], m)
			o += m + 1
			d *= n
		}
	}
	return f
}

// polyval is pj_polyval: sum(p[i] * x^i, i, 0, N).
func polyval(x float64, p []float64, n int) float64 {
	if n < 0 {
		return 0
	}
	y := p[n]
	for n > 0 {
		n--
		y = y*x + p[n]
	}
	return y
}

// clenshaw is pj_clenshaw: sum(F[k] * sin((2*k+2) * zeta)).
func clenshaw(szeta, czeta float64, f []float64) float64 {
	var u0, u1 float64
	x := 2 * (czeta - szeta) * (czeta + szeta)
	for k := len(f); k > 0; {
		k--
		t := x*u0 - u1 + f[k]
		u1, u0 = u0, t
	}
	return 2 * szeta * czeta * u0
}

// auxlatConvert is pj_auxlat_convert(zeta, F).
func auxlatConvert(zeta float64, f []float64) float64 {
	return zeta + clenshaw(math.Sin(zeta), math.Cos(zeta), f)
}

// auxlatConvertSC is pj_auxlat_convert(zeta, szeta, czeta, F).
func auxlatConvertSC(zeta, szeta, czeta float64, f []float64) float64 {
	return zeta + clenshaw(szeta, czeta, f)
}

// rectifyingRadius is pj_rectifying_radius.
func rectifyingRadius(n float64) float64 {
	return polyval(n*n, []float64{1, 1.0 / 4, 1.0 / 64, 1.0 / 256}, 3) / (1 + n)
}

// meridian holds pj_enfn's coefficients for the meridian distance.
type meridian struct {
	r        float64
	fwd, inv [auxOrder]float64
}

func newMeridian(n float64) *meridian {
	return &meridian{
		r:   rectifyingRadius(n),
		fwd: auxlatCoeffs(n, auxGeographic, auxRectifying),
		inv: auxlatCoeffs(n, auxRectifying, auxGeographic),
	}
}

// mlfn is pj_mlfn: the meridian distance to phi (in units of a).
func (m *meridian) mlfn(phi, sphi, cphi float64) float64 {
	return m.r * auxlatConvertSC(phi, sphi, cphi, m.fwd[:])
}

// invMlfn is pj_inv_mlfn.
func (m *meridian) invMlfn(mu float64) float64 {
	return auxlatConvert(mu/m.r, m.inv[:])
}

// msfn is pj_msfn.
func msfn(sinphi, cosphi, es float64) float64 {
	return cosphi / math.Sqrt(1-es*sinphi*sinphi)
}

// tsfn is pj_tsfn: exp(-psi), psi being the isometric latitude.
func tsfn(phi, sinphi, e float64) float64 {
	cosphi := math.Cos(phi)
	if sinphi > 0 {
		return math.Exp(e*math.Atanh(e*sinphi)) * (cosphi / (1 + sinphi))
	}
	return math.Exp(e*math.Atanh(e*sinphi)) * ((1 - sinphi) / cosphi)
}

// sinhpsi2tanphi is pj_sinhpsi2tanphi (GeographicLib's Math::tauf).
func sinhpsi2tanphi(taup, e float64) float64 {
	const numit = 5
	rooteps := math.Sqrt(2.220446049250313e-16)
	tol := rooteps / 10
	tmax := 2 / rooteps
	e2m := 1 - e*e
	stol := tol * math.Max(1, math.Abs(taup))
	var tau float64
	if math.Abs(taup) > 70 {
		tau = taup * math.Exp(e*math.Atanh(e))
	} else {
		tau = taup / e2m
	}
	if !(math.Abs(tau) < tmax) {
		return tau
	}
	for i := numit; i > 0; i-- {
		tau1 := math.Sqrt(1 + tau*tau)
		sig := math.Sinh(e * math.Atanh(e*tau/tau1))
		taupa := math.Sqrt(1+sig*sig)*tau - sig*tau1
		dtau := (taup - taupa) * (1 + e2m*(tau*tau)) / (e2m * tau1 * math.Sqrt(1+taupa*taupa))
		tau += dtau
		if !(math.Abs(dtau) >= stol) {
			break
		}
	}
	return tau
}

// phi2 is pj_phi2.
func phi2(ts0, e float64) float64 {
	return math.Atan(sinhpsi2tanphi((1/ts0-ts0)/2, e))
}

// authalic holds the coefficients of authalic latitude conversions.
type authalic struct {
	toGeo, fromGeo [auxOrder]float64
	series         bool // |n| < 0.01
	qp             float64
}

func newAuthalic(p ellipsoidParams) *authalic {
	a := &authalic{series: math.Abs(p.n) < 0.01}
	a.toGeo = auxlatCoeffs(p.n, auxAuthalic, auxGeographic)
	if a.series {
		a.fromGeo = auxlatCoeffs(p.n, auxGeographic, auxAuthalic)
	}
	a.qp = authalicQ(1, p)
	return a
}

// authalicQ is pj_authalic_lat_q.
func authalicQ(sinphi float64, p ellipsoidParams) float64 {
	const epsilon = 1e-7
	if p.e >= epsilon {
		esinphi := p.e * sinphi
		d := 1.0 - esinphi*esinphi
		if d == 0 {
			return math.Inf(1)
		}
		return p.oneEs * (sinphi/d + math.Atanh(esinphi)/p.e)
	}
	return 2 * sinphi
}

// lat is pj_authalic_lat.
func (a *authalic) lat(phi, sinphi, cosphi float64, p ellipsoidParams) float64 {
	if a.series {
		return auxlatConvertSC(phi, sinphi, cosphi, a.fromGeo[:])
	}
	q := authalicQ(sinphi, p)
	ratio := q / a.qp
	if math.Abs(ratio) > 1 {
		ratio = math.Copysign(1, ratio)
	}
	return math.Asin(ratio)
}

// inverse is pj_authalic_lat_inverse.
func (a *authalic) inverse(beta float64, p ellipsoidParams) float64 {
	phi := auxlatConvert(beta, a.toGeo[:])
	if a.series {
		return phi
	}
	q := math.Sin(beta) * a.qp
	qDiv := q / p.oneEs
	for range 10 {
		sinphi, cosphi := math.Sin(phi), math.Cos(phi)
		d := 1 - p.es*(sinphi*sinphi)
		dphi := (d * d) / (2 * cosphi) * (qDiv - sinphi/d - math.Atanh(p.e*sinphi)/p.e)
		if !(math.Abs(dphi) >= 1e-15) {
			break
		}
		phi += dphi
	}
	return phi
}

// adjlon is PROJ's adjlon: a longitude reduced to [-pi, pi].
func adjlon(lon float64) float64 {
	if math.Abs(lon) < math.Pi+1e-12 {
		return lon
	}
	lon += math.Pi
	lon -= 2 * math.Pi * math.Floor(lon/(2*math.Pi))
	return lon - math.Pi
}

func aasin(v float64) float64 {
	if math.Abs(v) >= 1 {
		return math.Copysign(math.Pi/2, v)
	}
	return math.Asin(v)
}

func aatan2(n, d float64) float64 {
	if math.Abs(n) < 1e-50 && math.Abs(d) < 1e-50 {
		return 0
	}
	return math.Atan2(n, d)
}
