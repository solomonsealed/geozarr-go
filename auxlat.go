import "math"

// The projections follow PROJ (https://proj.org) 9.8, the version pyproj
// bundles, so that coordinates agree with pyproj to the last few bits.
// This file holds PROJ's ellipsoid parameters and auxiliary latitudes
// (src/ell_set.cpp, src/latitudes.cpp, src/phi2.cpp, src/tsfn.cpp, ...),
// after C. F. F. Karney, On auxiliary latitudes, Survey Review 56 (2024).

const degToRad = math.Pi / 180

// ellipsoidParams are PROJ's derived ellipsoid parameters.
type ellipsoidParams struct {
	a     float64 // semi-major axis
	es    float64 // eccentricity squared
	e     float64 // eccentricity
	oneEs float64 // 1 - es
	n     float64 // third flattening
}

// newEllipsoidParams derives PROJ's parameters from a and the inverse
// flattening rf (0 for a sphere), as PROJ does for +a +rf.
func newEllipsoidParams(a, rf float64) ellipsoidParams {
	p := ellipsoidParams{a: a}
	if rf != 0 {
		f := 1 / rf
		p.es = 2*f - f*f
	}
	p.e = math.Sqrt(p.es)
	alpha := math.Asin(p.e)
	p.n = math.Pow(math.Tan(alpha/2), 2)
	p.oneEs = 1 - p.es
	return p
}

