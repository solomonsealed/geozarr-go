def main():
    entries = {}
    for code in GEOGRAPHIC + PROJECTED:
        try:
            crs = pyproj.CRS.from_epsg(code)
        except pyproj.exceptions.CRSError:
            continue
        p4 = crs.to_proj4()
        if crs.coordinate_operation is not None and crs.coordinate_operation.method_code == "1024":
            # Pseudo-Mercator: PROJ projects it with webmerc (its PROJ
            # string's spherical merc is equivalent, but loses the method).
            p4 = "+" + crs.coordinate_operation.to_proj4().split("+step +")[-1]
        if not p4:
            continue
        parts = [p for p in p4.split() if not p.startswith(("+type=", "+no_defs", "+towgs84=", "+nadgrids=", "+wktext"))]
        proj = next((p.split("=", 1)[1] for p in parts if p.startswith("+proj=")), None)
        if proj not in SUPPORTED or any(p.startswith(("+axis=", "+pm=", "+approx")) for p in parts):
            continue
        entries[code] = (" ".join(parts), crs.name)
    lines = [
        "// Code generated by consistency/gen_epsg.py from pyproj " + pyproj.__version__ + " (PROJ " + pyproj.proj_version_str + "); DO NOT EDIT.",
        "",
        "package geozarr",
        "",
        "// epsgTable holds PROJ strings and names of common EPSG CRSs.",
        "var epsgTable = map[int][2]string{",
    ]
    for code in sorted(entries):
        p4, name = entries[code]
        lines.append(f"\t{code}: {{{go_str(p4)}, {go_str(name)}}},")
    lines.append("}")
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crs_epsg_table.go")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(entries)} codes")


def go_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


if __name__ == "__main__":
    main()
